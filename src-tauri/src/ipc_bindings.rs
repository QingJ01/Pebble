//! Generated TypeScript bindings for IPC-facing Rust types.
//!
//! `src/lib/generated/ipc.ts` is produced from the `ts_rs::TS` derives on the
//! types listed below. The test fails when the checked-in file is stale;
//! regenerate with:
//!
//! ```sh
//! UPDATE_IPC_BINDINGS=1 cargo test -p pebble ipc_bindings
//! ```

use std::path::PathBuf;
use ts_rs::{Config, TS};

macro_rules! decls {
    ($cfg:expr; $($ty:ty),* $(,)?) => {
        vec![$( (<$ty as TS>::name($cfg), <$ty as TS>::decl($cfg)) ),*]
    };
}

fn render() -> String {
    // Timestamps/sizes are i64/u64/usize in Rust but always fit in a JS number.
    let cfg = &Config::new().with_large_int("number");
    let mut decls = decls![cfg;
        // pebble-core
        pebble_core::Account,
        pebble_core::ProviderType,
        pebble_core::HttpProxyConfig,
        pebble_core::Folder,
        pebble_core::FolderType,
        pebble_core::FolderRole,
        pebble_core::Message,
        pebble_core::MessageSummary,
        pebble_core::EmailAddress,
        pebble_core::Attachment,
        pebble_core::KanbanColumn,
        pebble_core::KanbanCard,
        pebble_core::SnoozedMessage,
        pebble_core::TrustedSender,
        pebble_core::TrustType,
        pebble_core::Rule,
        pebble_core::PrivacyMode,
        pebble_core::RenderedHtml,
        pebble_core::TrackerInfo,
        pebble_core::TranslateConfig,
        pebble_core::ThreadSummary,
        pebble_core::KnownContact,
        pebble_core::ContactEmailLabel,
        pebble_core::ContactEmail,
        pebble_core::Contact,
        pebble_core::ContactEmailInput,
        pebble_core::ContactInput,
        pebble_core::ContactSuggestionSource,
        pebble_core::ContactSuggestion,
        pebble_core::VcardImportResult,
        // other crates
        pebble_mail::ConnectionSecurity,
        pebble_store::labels::Label,
        pebble_store::cloud_sync::BackupPreview,
        pebble_translate::types::TranslateResult,
        pebble_translate::types::BilingualSegment,
        // src-tauri command types
        crate::commands::accounts::AddAccountRequest,
        crate::commands::network::AccountProxyMode,
        crate::commands::network::AccountProxySetting,
        crate::commands::diagnostics::AppLogSnapshot,
        crate::commands::appearance::ImportedBackgroundImage,
        crate::commands::notifications::NotificationStatus,
        crate::commands::notifications::NotificationLabels,
        crate::commands::advanced_search::AdvancedSearchQuery,
        crate::commands::folders::ImapSyncFolderSettings,
        crate::commands::batch::BatchMarkReadResult,
        crate::commands::pending_mail_ops::PendingMailOpsSummaryResponse,
        crate::commands::pending_mail_ops::PendingMailOpResponse,
        pebble_core::traits::SearchHit,
    ];
    decls.sort_by(|a, b| a.0.cmp(&b.0));
    let mut out = String::from(
        "// This file is generated by src-tauri/src/ipc_bindings.rs. Do not edit.\n\
         // Regenerate: UPDATE_IPC_BINDINGS=1 cargo test -p pebble ipc_bindings\n",
    );
    for (_, decl) in decls {
        out.push('\n');
        out.push_str("export ");
        out.push_str(decl.trim());
        out.push('\n');
    }
    out
}

fn bindings_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/lib/generated/ipc.ts")
}

#[test]
fn generated_ipc_bindings_are_up_to_date() {
    let expected = render();
    let path = bindings_path();
    if std::env::var_os("UPDATE_IPC_BINDINGS").is_some() {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &expected).unwrap();
        return;
    }
    let actual = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        actual.replace("\r\n", "\n") == expected,
        "{} is stale; regenerate with `UPDATE_IPC_BINDINGS=1 cargo test -p pebble ipc_bindings`",
        path.display()
    );
}
